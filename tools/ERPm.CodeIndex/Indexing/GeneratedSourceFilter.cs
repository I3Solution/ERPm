namespace ERPm.CodeIndex.Indexing;

public static class GeneratedSourceFilter
{
    private const int HeaderScanLength = 2048;

    public static bool ShouldInclude(
        string sourcePath,
        string repositoryPath,
        string? sourceText = null)
    {
        if (string.IsNullOrWhiteSpace(sourcePath))
        {
            return false;
        }

        var relativePath = Path.GetRelativePath(repositoryPath, sourcePath)
            .Replace('\\', '/');

        if (Path.IsPathRooted(relativePath)
            || relativePath == ".."
            || relativePath.StartsWith("../", StringComparison.Ordinal))
        {
            return false;
        }

        var segments = relativePath.Split('/', StringSplitOptions.RemoveEmptyEntries);
        if (segments.Any(segment =>
            segment.Equals("obj", StringComparison.OrdinalIgnoreCase)
            || segment.Equals("bin", StringComparison.OrdinalIgnoreCase)))
        {
            return false;
        }

        var fileName = segments.LastOrDefault() ?? relativePath;
        if (fileName.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || fileName.EndsWith(".g.i.cs", StringComparison.OrdinalIgnoreCase)
            || fileName.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        if (!string.IsNullOrEmpty(sourceText))
        {
            var header = sourceText[..Math.Min(HeaderScanLength, sourceText.Length)];
            if (header.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase))
            {
                return false;
            }
        }

        return true;
    }
}
