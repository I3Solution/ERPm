using ERPm.CodeIndex.Indexing;

namespace ERPm.CodeIndex.Tests;

public sealed class GeneratedSourceFilterTests
{
    private static readonly string RepositoryRoot =
        Path.GetFullPath(Path.Combine(Path.GetTempPath(), "erpm-code-index-fixture"));

    [Theory]
    [InlineData("src/obj/Debug/net10.0/Generated.cs")]
    [InlineData("src/bin/Debug/net10.0/Generated.cs")]
    [InlineData("SRC/OBJ/Generated.cs")]
    [InlineData("src/Generated.g.cs")]
    [InlineData("src/Generated.G.CS")]
    [InlineData("src/Generated.generated.cs")]
    public void Excludes_build_and_convention_generated_paths(string relativePath)
    {
        var fullPath = Path.Combine(RepositoryRoot, relativePath.Replace('/', Path.DirectorySeparatorChar));

        Assert.False(GeneratedSourceFilter.ShouldInclude(fullPath, RepositoryRoot));
    }

    [Fact]
    public void Excludes_auto_generated_header_even_for_designer_file()
    {
        var path = Path.Combine(RepositoryRoot, "src", "Form.Designer.cs");

        Assert.False(GeneratedSourceFilter.ShouldInclude(
            path,
            RepositoryRoot,
            "// <auto-generated />\nnamespace Fixture;"));
    }

    [Fact]
    public void Includes_handwritten_designer_file_without_generated_marker()
    {
        var path = Path.Combine(RepositoryRoot, "src", "Form.Designer.cs");

        Assert.True(GeneratedSourceFilter.ShouldInclude(
            path,
            RepositoryRoot,
            "namespace Fixture;\ninternal sealed class FormDesigner {}"));
    }

    [Fact]
    public void Excludes_source_outside_repository_root()
    {
        var path = Path.GetFullPath(Path.Combine(RepositoryRoot, "..", "Shared", "Linked.cs"));

        Assert.False(GeneratedSourceFilter.ShouldInclude(path, RepositoryRoot));
    }
}
